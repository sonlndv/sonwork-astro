import { readFileSync, writeFileSync, existsSync } from 'node:fs';

// Build-only J2000 projection. These are the approved Home coordinates, magnitude hierarchy,
// colours and reading-corridor hush; every route uses the same art. No executable SVG content.
const poses = {
  wide: { ra0: 335, dec0: -5, cx: 1130, cy: -50, scale: 850, x: [-100, 1700], y: [-280, 380], grow: 1,
    hush: [[285, -118, 610, -55], [285, -32, 1020, 24], [285, 26, 760, 56], [285, 78, 870, 100], [285, 118, 930, 400], [285, 270, 1310, 700]] },
  tall: { ra0: 335, dec0: -5, cx: 320, cy: -25, scale: 360, x: [-20, 420], y: [-125, 180], grow: 1.15,
    hush: [[5, -55, 265, 3], [5, 30, 145, 50], [-20, 68, 420, 200]] },
};
const anchors = new Set([110395, 110960, 111497, 110672, 109074, 106278, 113136]);
const tint = bv => (bv < 0.15 ? '#cfe0ff' : bv < 0.55 ? '#f4f6ff' : bv < 0.9 ? '#ffeacf' : '#ffc99a');
// Four user units of transparent overscan retain the complete outermost point (maximum radius 2.6).
export const starSkyBounds = Object.fromEntries(Object.entries(poses).map(([name, p]) => [name,
  [p.x[0] - 4, p.y[0] - 4, p.x[1] - p.x[0] + 8, p.y[1] - p.y[0] + 8],
]));

export function writeStarSky() {
  const { stars: rows } = JSON.parse(readFileSync(new URL('../src/assets/home-star-catalog.json', import.meta.url), 'utf8'));
  const rad = Math.PI / 180;
  for (const [name, p] of Object.entries(poses)) {
    const d0 = p.dec0 * rad;
    const points = [];
    for (const [hip, ra, declination, mag, bv] of rows) {
      const dec = declination * rad, dra = (ra - p.ra0) * rad;
      const den = Math.sin(d0) * Math.sin(dec) + Math.cos(d0) * Math.cos(dec) * Math.cos(dra);
      if (den <= 0.15) continue;
      const x = p.cx - p.scale * Math.cos(dec) * Math.sin(dra) / den;
      const y = p.cy - p.scale * (Math.cos(d0) * Math.sin(dec) - Math.sin(d0) * Math.cos(dec) * Math.cos(dra)) / den;
      if (x < p.x[0] || x > p.x[1] || y < p.y[0] || y > p.y[1]) continue;
      points.push({ x, y, mag, bv, hip });
    }
    points.sort((a, b) => a.mag - b.mag);
    const circles = points.slice(0, 600).map(({ x, y, mag, bv, hip }) => {
      const quiet = p.hush.some(h => x >= h[0] && x <= h[2] && y >= h[1] && y <= h[3]);
      const lum = Math.max(0, 6 - mag);
      const r = Math.min(2.6, Math.max(0.85, (0.8 + lum * 0.34 + Math.max(0, lum - 3) * 0.4) * p.grow * (anchors.has(hip) ? 1.5 : 1) * (quiet ? 0.85 : 1)));
      const opacity = Math.min(anchors.has(hip) ? 0.95 : 1, Math.max(0.82, 0.6 + lum * 0.14) * (anchors.has(hip) ? 1.3 : 1)) * (quiet ? 0.45 : 1);
      return `<circle cx="${x.toFixed(2)}" cy="${y.toFixed(2)}" r="${r.toFixed(2)}" fill="${tint(bv)}" opacity="${opacity.toFixed(2)}"/>`;
    });
    const bounds = starSkyBounds[name];
    const svg = `<!-- Generated by scripts/generate-star-sky.mjs; catalogue credit: /mountains/home-star-catalog.LICENSE.txt -->\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="${bounds.join(' ')}" width="${bounds[2]}" height="${bounds[3]}">${circles.join('')}</svg>\n`;
    const target = new URL(`../src/assets/home-star-sky-${name}.svg`, import.meta.url);
    if (!existsSync(target) || readFileSync(target, 'utf8') !== svg) writeFileSync(target, svg);
  }
}
